// Returns '; advice' for a known code, otherwise ''.
export function hintFor(code: string | undefined): string {
  const hint = code === undefined ? undefined : Object.hasOwn(HINTS, code) ? HINTS[code] : undefined;
  return hint ? `; ${hint}` : '';
}
